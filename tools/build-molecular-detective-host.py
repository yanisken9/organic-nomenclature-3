"""Generate the isolated expanded-2D Detective viewer from composed local Main57."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mulermoc-nom-57.html"
DEST = ROOT / "games/molecular-detective-viewer.html"
INIT = ROOT / "spt/init-57.spt"
BRIDGE = ROOT / "js/namelecule-molecular-detective-host.js"
ALKANE_DATA = ROOT / "js/MULERMOC_namelecule_alkanes_v1_data.js"


def generate():
    original = SOURCE.read_text(encoding="utf-8")
    source, count = re.subn(
        r"  <!-- Google tag \(gtag.js\) -->.*?(?=  <title>)", "", original,
        count=1, flags=re.S,
    )
    assert count == 1, "Expected the Main57 analytics block"
    # The original document, native scripts, source MOLs and hidden JSmol
    # lifecycle remain unchanged. Only this generated child has this shell.
    early = '''
  <base href="../" />
  <!-- Generated by tools/build-molecular-detective-host.py; do not edit. -->
  <script>
    window.MULER_QUIET_FETCH = true;
    window.__mulerStepLang = 'gr';
    (function () {
      var params = new URLSearchParams(location.search);
      var formulaPx = params.get('nlFormulaPx');
      var pixels = Number(formulaPx);
      if (parent !== window && /^[0-9]+(?:[.][0-9]+)?$/.test(formulaPx || '') &&
          Number.isFinite(pixels) && pixels >= 20 && pixels <= 36) {
        document.documentElement.setAttribute('data-namelecule-2d-font-size', String(pixels));
      }
      var session = params.get('session');
      if (parent === window || !/^[A-Za-z0-9_-]{16,128}$/.test(session || '')) return;
      window.__molecularDetectiveStartupTimer = setTimeout(function () {
        if (window.__molecularDetectiveStarted) return;
        window.__molecularDetectiveStartupFailed = true;
        parent.postMessage({channel:'namelecule-molecular-detective-v1', session:session,
          requestId:0, roundId:null, moleculeId:null, type:'error', code:'STARTUP_TIMEOUT',
          message:'Η προβολή μορίου δεν μπόρεσε να ξεκινήσει. Δοκίμασε ξανά.'}, location.origin);
      }, 30000);
    })();
  </script>
  <style>
    html, body { margin:0!important; padding:0!important; min-width:0!important;
      width:100%!important; height:100%!important; overflow:hidden!important; background:#fff!important; }
    body > :not(#pageContainer), #pageContainer > :not(#authorLayout),
    #authorLayout > :not(#mainAppContainer), .mainApp3Columns > :not(#viewerCol),
    #viewerCol > :not(#jsmeNomeclatureDIV):not(#nomeclature3D) { display:none!important; }
    #pageContainer, #authorLayout, #mainAppContainer, .mainApp3Columns, #viewerCol {
      display:block!important; margin:0!important; padding:0!important;
      width:100%!important; min-width:0!important; max-width:none!important;
      border:0!important; box-shadow:none!important; background:#fff!important; }
    #viewerCol { height:100vh!important; }
    html:not([data-molecular-detective-visible="true"]) #viewerCol { visibility:hidden!important; }
    #nomeclature3D, #analysisCol, #nameAnalysis, #nameAnalysisExplain, #moleculeInfo,
    #scenarioPlayBar, #scenarioAuthorBar, #creditsUs, #rotatePrompt, #lessonLoading,
    .nameExplainPortal, [role="tooltip"] { display:none!important; }
    #jsmeNomeclatureDIV, #jsmeNomeclatureSVG {
      margin:0!important; padding:0!important; border:0!important; max-width:100%!important; }
    #jsmeNomeclatureSVG { touch-action:manipulation; }
  </style>
'''
    assert source.count("<head>") == 1
    source = source.replace("<head>", "<head>\n" + early, 1)
    # Main57 already loads the accepted custom records through its native
    # post-fInitData path. Refresh that single bundle reference, never inject it.
    bundle_digest = hashlib.sha256(ALKANE_DATA.read_bytes()).hexdigest()
    source, count = re.subn(
        r'(src="js/MULERMOC_namelecule_alkanes_v1_data\.js)(?:\?[^"\n]*)?"',
        lambda match: match[1] + '?v=' + bundle_digest + '"', source,
    )
    assert count == 1, "Expected exactly one Main57 custom-alkane bundle"
    assert re.search(r'src="js/jsme-nick-nomeclature-moc2-data_57\.js(?:\?[^"\n]*)?"', source), \
        "Expected the Main57 base-data script"
    init_digest = hashlib.sha256(INIT.read_bytes()).hexdigest()
    init_command = 'script "spt/init-57.spt?v=' + init_digest + '";'
    config = '''<script>
    JSmol_Applet.script = 'set defaultDirectory ' + JSON.stringify(new URL('../', location.href).href) + ';set disablePopupMenu true;';
    (function () {
      const nativeScript = Jmol.script;
      Jmol.script = function (applet, command) {
        const updated = typeof command === 'string'
          ? command.replaceAll('script spt/init-57.spt;', __INIT_COMMAND__)
          : command;
        return nativeScript.call(this, applet, updated);
      };
    })();
  </script>
'''.replace("__INIT_COMMAND__", json.dumps(init_command))
    source = source.replace("</head>", config + "</head>", 1)
    source = source.replace("<title>Namelecule — Ονοματολογία Οργανικών Ενώσεων</title>",
                            "<title>Namelecule — Μοριακός Ντετέκτιβ</title>", 1)
    bridge_digest = hashlib.sha256(BRIDGE.read_bytes()).hexdigest()
    bridge = '<script src="js/namelecule-molecular-detective-host.js?v=' + bridge_digest + '"></script>\n'
    assert source.count("</body>") == 1
    source = source.replace("</body>", bridge + "</body>", 1)
    # Bind every real local script and stylesheet in the generated child to
    # its bytes, including native57 dependencies. Leave example tags in HTML
    # comments untouched; they are not loaded and may refer to absent bundles.
    def bind_asset(match):
        asset = ROOT / match[2]
        assert asset.is_file(), "Missing local Detective dependency: " + match[2]
        digest = hashlib.sha256(asset.read_bytes()).hexdigest()
        return match[1] + match[2] + '?v=' + digest + '"'

    parts = re.split(r'(<!--.*?-->)', source, flags=re.S)
    for index in range(0, len(parts), 2):
        parts[index] = re.sub(r'((?:src|href)=")((?:js|css)/[^"?\n]+)(?:\?[^"\n]*)?"',
                              bind_asset, parts[index])
    source = ''.join(parts)
    return source, hashlib.sha256(original.encode("utf-8")).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, digest = generate()
    if args.check:
        assert DEST.read_text(encoding="utf-8") == source, "Rebuild Molecular Detective host"
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(source, encoding="utf-8")
    print(("Verified" if args.check else "Generated") + " Main57 Detective host; source SHA-256 " + digest)


if __name__ == "__main__":
    main()
