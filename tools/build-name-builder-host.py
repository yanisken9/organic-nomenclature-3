"""Generate the isolated name-builder viewer from the unchanged Main55 page."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mulermoc-nom-55.html"
DEST = ROOT / "games/name-builder-viewer.html"
INIT = ROOT / "spt/init-55.spt"


def generate():
    original = SOURCE.read_text(encoding="utf-8")
    source, count = re.subn(
        r"  <!-- Google tag \(gtag.js\) -->.*?(?=  <title>)", "", original,
        count=1, flags=re.S,
    )
    assert count == 1, "Expected the Main55 analytics block"
    # Only this generated document changes. Native scripts, source molecules,
    # geometry, nomenclature and JSmol lifecycle remain the Main55 versions.
    early = '''
  <base href="../" />
  <!-- Generated by tools/build-name-builder-host.py; do not edit this file. -->
  <script>
    window.MULER_QUIET_FETCH = true;
    window.__mulerStepLang = 'gr';
    // A bounded failure response also works if a later native script fails.
    (function () {
      var session = new URLSearchParams(location.search).get('session');
      if (parent === window || !/^[A-Za-z0-9_-]{16,128}$/.test(session || '')) return;
      window.__nameBuilderStartupTimer = setTimeout(function () {
        if (window.__nameBuilderStarted) return;
        window.__nameBuilderStartupFailed = true;
        parent.postMessage({channel:'namelecule-name-builder-v1', session:session,
          type:'error', code:'STARTUP_TIMEOUT',
          message:'Η προβολή μορίου δεν μπόρεσε να ξεκινήσει. Δοκίμασε ξανά.',
          requestId:0, roundId:null, moleculeId:null}, location.origin);
      }, 30000);
    })();
  </script>
  <style>
    html, body { margin:0!important; padding:0!important; min-width:0!important;
      width:100%!important; height:100%!important; overflow:hidden!important; background:#fff!important; }
    body > :not(#pageContainer), #pageContainer > :not(#authorLayout),
    #authorLayout > :not(#mainAppContainer), .mainApp3Columns > :not(#viewerCol),
    #viewerCol > :not(#jsmeNomeclatureDIV):not(#nomeclature3D) { display:none!important; }
    #pageContainer, #authorLayout, #mainAppContainer, .mainApp3Columns, #viewerCol {
      display:block!important; margin:0!important; padding:0!important;
      width:100%!important; min-width:0!important; max-width:none!important;
      border:0!important; box-shadow:none!important; background:#fff!important; }
    #viewerCol { height:100vh!important; }
    html:not([data-name-builder-visible="true"]) #viewerCol { visibility:hidden!important; }
    html[data-name-builder-representation="3d"] #jsmeNomeclatureDIV,
    html[data-name-builder-representation="2d"] #nomeclature3D { display:none!important; }
    #jsmeNomeclatureDIV, #jsmeNomeclatureSVG, #nomeclature3D {
      margin:0!important; padding:0!important; border:0!important; max-width:100%!important; }
    #analysisCol, #nameAnalysis, #nameAnalysisExplain, #moleculeInfo,
    #scenarioPlayBar, #scenarioAuthorBar, #creditsUs, #rotatePrompt, #lessonLoading,
    .nameExplainPortal, [role="tooltip"] { display:none!important; }
  </style>
'''
    assert source.count("<head>") == 1
    source = source.replace("<head>", "<head>\n" + early, 1)
    # Model-relative SDF and init-script loads use the same repository base as
    # the original page, including after JSmol has asynchronously started.
    init_digest = hashlib.sha256(INIT.read_bytes()).hexdigest()
    init_command = 'script "spt/init-55.spt?v=' + init_digest + '";'
    config = '''<script>
    JSmol_Applet.script = 'set defaultDirectory ' + JSON.stringify(new URL('../', location.href).href) + ';set disablePopupMenu true;';
    // The host shares native3D initialization, with a content-bound URL so
    // JSmol cannot silently reuse a previous cached version of that script.
    // The Main55 page and all other native commands remain unchanged.
    (function () {
      const nativeScript = Jmol.script;
      Jmol.script = function (applet, command) {
        const updated = typeof command === 'string'
          ? command.replaceAll('script spt/init-55.spt;', __INIT_COMMAND__)
          : command;
        return nativeScript.call(this, applet, updated);
      };
    })();
  </script>
'''
    config = config.replace("__INIT_COMMAND__", json.dumps(init_command))
    source = source.replace("</head>", config + "</head>", 1)
    source = source.replace("<title>Namelecule — Ονοματολογία Οργανικών Ενώσεων</title>",
                            "<title>Namelecule — Προβολή μορίου</title>", 1)
    bridge = '<script src="js/namelecule-name-builder-host.js?v=prototype-20261111-r1"></script>\n'
    source = source.replace("</body>", bridge + "</body>", 1)
    digest = hashlib.sha256(original.encode("utf-8")).hexdigest()
    return source, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, digest = generate()
    if args.check:
        assert DEST.read_text(encoding="utf-8") == source, "Rebuild name-builder host"
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(source, encoding="utf-8")
    print(("Verified" if args.check else "Generated") + " Main55 name-builder host; source SHA-256 " + digest)


if __name__ == "__main__":
    main()
